#
# 【统计方法核心】
# - PCA：线性降维，把高维蛋白组合成少数主成分（PC1/PC2）
# - 解释方差比例：衡量主成分信息量
# - 置信椭圆：展示分组分布范围与分离趋势
#
# 【代码逻辑（逐步）】
# 1) 合并状态数据与蛋白数据
# 2) 提取显著蛋白并标准化
# 3) 做个体层面 PCA
# 4) 做年龄分层聚合后的 PCA
# 5) 绘制状态颜色分组与95%椭圆
#
# 【初学者提示】
# - PCA 仅反映主要变异方向，不直接等价于因果关系
# - 若组间明显分离，提示分子谱存在轨迹特异性
