# ==================== 脚本开头综合概括 ====================
# 原脚本：MainAnalysis/2. KM_Plot and RMST_Calculation.R
# 目的：用 Kaplan-Meier 曲线展示不同轨迹组生存差异，并用 RMST 量化差异。
#
# 【统计方法核心】
# - KM：非参数生存函数估计
# - RMST（限制平均生存时间）：在固定随访窗（如15年）内比较平均生存时长
#
# 【代码逻辑（逐步）】
# 1) 根据转移指示定义 status（健康/CMD/CA/CMD-CA/CA-CMD）
# 2) 定义各状态的起算时间（例如从第二事件后开始计生存）
# 3) 拟合 survfit 曲线并绘图
# 4) 用 survRM2 计算 RMST 差值与显著性
#
# 【初学者提示】
# - RMST 对“比例风险假设不完全成立”时更稳健、更直观
# - 要确保不同状态的 time origin 定义一致且有临床意义
# ==================== 脚本结尾综合概括 ====================
# 本脚本把“轨迹风险”转化为“生存时间损失/获益”的可解释指标，
# 对临床沟通和分层管理非常关键。
