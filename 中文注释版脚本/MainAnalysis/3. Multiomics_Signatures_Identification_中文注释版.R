# ==================== 脚本开头综合概括 ====================
# 原脚本：MainAnalysis/3. Multiomics_Signatures_Identification.R
# 目的：在多状态轨迹框架下识别多组学标志物（重点蛋白）并准备训练/测试数据。
#
# 【多组学在本项目的意义】
# - 让“临床轨迹”与“分子层变化”建立联系
# - 为机制解释（为什么会转移）和预测（谁会转移）提供证据
#
# 【统计/机器学习要点】
# - 高维特征标准化（z-score）
# - 训练/测试划分（避免过拟合）
# - 协变量调整（减少混杂）
#
# 【代码逻辑（逐步）】
# 1) 读入 CMD_CA、协变量、蛋白数据
# 2) 对蛋白矩阵做标准化
# 3) 按规则划分训练/测试集
# 4) 为后续富集、PCA、LASSO、ROC 脚本准备输入
#
# 【初学者提示】
# - 高维组学分析中，标准化和数据分割是基础中的基础
# - 多组学结果应尽量在独立数据中验证稳定性
# ==================== 脚本结尾综合概括 ====================
# 本脚本是多组学分析的“数据与特征准备中枢”，
# 为后续机制解释与预测建模打通输入链路。
