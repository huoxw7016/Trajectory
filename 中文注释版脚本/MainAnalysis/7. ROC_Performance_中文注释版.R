# ==================== 脚本开头综合概括 ====================
# 原脚本：MainAnalysis/7. ROC_Performance.R
# 目的：比较多种预测模型在不同转移上的时间依赖 ROC/AUC 表现。
#
# 【统计方法核心】
# - 时间依赖 ROC（riskRegression::Score）
# - 以 Cox 模型为基础比较 10 年时点判别能力
# - 输出 AUC 与模型间比较 p 值
#
# 【模型体系】
# - Base / Lifestyle / PRS / Clinical / Metabolomics / Proteomics / Combined
#
# 【代码逻辑（逐步）】
# 1) 读入各类风险评分与协变量
# 2) 循环 9 个转移终点
# 3) 拟合 7 种 Cox 预测模型
# 4) 计算并绘制 10 年 ROC，记录 AUC 与对比统计
#
# 【初学者提示】
# - AUC 越高，区分高低风险能力越好；但也要关注校准与临床可用性
# - “Combined模型提升幅度”是多组学增益价值的直观证据
# ==================== 脚本结尾综合概括 ====================
# 本脚本把“候选标志物”转化为“可量化预测性能”，
# 是评价多组学整合是否真正有临床增益的关键环节。
