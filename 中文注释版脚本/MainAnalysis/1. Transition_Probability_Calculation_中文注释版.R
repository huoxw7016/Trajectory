# ==================== 脚本开头综合概括 ====================
# 原脚本：MainAnalysis/1. Transition_Probability_Calculation.R
# 目的：估计多状态转移概率（含标准误），量化不同阶段病程的动态风险。
#
# 【统计方法核心】
# - mstate 框架：先定义转移矩阵 transMat
# - Cox 比例风险模型：对每条转移边建模（可含协变量）
# - probtrans：给定起始状态与时间点（如5/10/15年）计算转移概率
#
# 【输入输出】
# - 输入：CMD_CA.csv + covariates_impute.csv
# - 输出：all_trans.csv（各转移概率与SE）
#
# 【代码逻辑（逐步）】
# 1) 构建 long format 多状态数据
# 2) 扩展协变量并拟合 Cox
# 3) 分阶段计算：Baseline->(CMD/CA/Death)、CMD->(CMD+CA/Death)、
#    CA->(CA+CMD/Death)、共病后->Death
# 4) 汇总各阶段在多个时间点的转移概率与不确定性
#
# 【初学者提示】
# - 该分析回答“未来 t 年最可能转到哪个状态”
# - 与普通单终点Cox相比，能同时建模多个竞争路径
# ==================== 脚本结尾综合概括 ====================
# 本脚本提供了疾病轨迹研究的核心量化结果：
# 不仅知道“风险高低”，还知道“风险流向与时间演化”。
