# ==================== 脚本开头综合概括 ====================
# 原脚本：DataPreparation/3. UKB_Disease_Trajectory_Analysis.R
# 目的：把事件数据重构为多状态（multistate）分析所需的“转移结构数据”。
#
# 【研究问题】
# 个体可能经历：健康 -> CMD 或 CA -> CMD+CA（共病） -> 死亡。
# 该脚本负责定义每条路径是否发生、何时开始、何时结束。
#
# 【输出核心】
# - trans1 ~ trans9：9种转移事件指示
# - time*_from / time*_to：对应转移区间时间
# - 产出 CMD_CA.csv（后续主分析核心输入）
#
# 【统计方法要点】
# - 多状态建模的数据工程步骤（状态 + 转移 + 区间）
# - 逻辑分支枚举不同临床轨迹（含死亡先后顺序）
#
# 【代码逻辑（逐步）】
# 1) 定义复合状态 CD（心代谢疾病集合）
# 2) 清理时间逻辑异常样本
# 3) 按“是否发生CMD/CA/死亡及发生顺序”分类
# 4) 为每类样本写入转移指示与转移时间窗
#
# 【初学者提示】
# - 多状态模型不是只看终点，而是看“状态之间如何跳转”
# - 转移时间窗定义错误会直接导致风险估计偏差
# ==================== 脚本结尾综合概括 ====================
# 本脚本是全项目最关键的数据结构化步骤：
# 让复杂的真实病程变成可用 Cox-mstate 估计的标准转移数据。
