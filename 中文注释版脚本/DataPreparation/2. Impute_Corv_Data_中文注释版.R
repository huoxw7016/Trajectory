# ==================== 脚本开头综合概括 ====================
# 原脚本：DataPreparation/2. Impute_Corv_Data.R
# 目的：对协变量缺失值进行多重插补（MICE），得到可直接建模的完整数据。
#
# 【为什么重要】
# - 真实队列数据常有缺失；直接删样本会降低样本量并引入偏倚。
# - 多重插补通过“多次模拟 + 合并”更稳健。
#
# 【统计方法核心】
# - mice(m=5, maxit=5)
# - 连续变量：norm
# - 二分类变量：logreg
# - 多分类变量：polyreg
# - 有序分类：polr
#
# 【代码逻辑（逐步）】
# 1) 读取 covariates.csv，并把分类变量转成 factor
# 2) 指定不同变量的插补方法
# 3) 生成 5 套完整数据
# 4) 连续变量按行取均值；分类变量按行取众数
# 5) 输出 covariates_impute.csv
#
# 【初学者提示】
# - 插补前要确认变量类型（数值/无序分类/有序分类）是否正确
# - 插补结果应做分布检查，防止异常值被“过度平滑”
# ==================== 脚本结尾综合概括 ====================
# 本脚本把“有缺失的协变量”变成“可用于回归建模的完整矩阵”，
# 是保证后续 Cox、多状态、预测模型稳定性的基础步骤。
