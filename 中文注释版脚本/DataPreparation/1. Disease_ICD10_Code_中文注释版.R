# ==================== 脚本开头综合概括 ====================
# 原脚本：DataPreparation/1. Disease_ICD10_Code.R
# 目的：从 UKB 的 ICD-10 诊断编码中定义疾病事件（是否发生）与事件时间（何时发生）。
# 你可以把它理解为：把“原始住院/死亡编码”翻译成“分析可用的疾病标签和时间轴”。
#
# 【输入】
# - 个体基线日期（如 s_53_0_0）
# - ICD10 诊断编码字段（如 s_41270_0_*）
# - ICD10 对应日期字段（如 s_41280_0_*）
#
# 【输出（示例）】
# - event_dia / time_dia（糖尿病事件与时间）
# - event_CVD / time_CVD（心血管病事件与时间）
# - event_多癌种 / time_多癌种
# - death2_icd10 / death2_time（全因死亡）
#
# 【统计与方法要点】
# - ICD10 模式匹配（grepl）：按编码规则识别疾病
# - 最早发生时间提取（min）：同一疾病可能多条记录，取首次发生
# - 时间统一化：用“事件日期 - 基线日期”得到随访时间（年）
#
# 【代码逻辑（逐步）】
# 1) 逐个受试者遍历 ICD10 编码列
# 2) 对每种疾病定义对应编码规则
# 3) 若匹配成功，记录事件=1，并提取最早日期
# 4) 转换为相对时间并写回数据框
#
# 【初学者提示】
# - 该脚本是全项目“时间定义”的根，后续转移分析都依赖这里的时间准确性
# - 若疾病编码规则改动，后续全部结果都会变化
# ==================== 脚本结尾综合概括 ====================
# 本脚本完成了“从编码到事件时间”的关键第一步：
# 把离散、复杂的医疗编码，变成结构化的疾病发生变量，
# 为后续多状态转移建模提供可靠输入。
