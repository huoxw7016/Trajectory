# ==================== 脚本开头综合概括 ====================
# 原脚本：DataPreparation/4. Subgroup_Definition.R
# 目的：定义亚组（肿瘤分期、代谢控制、癌种生存率），支持分层分析。
#
# 【为什么做亚组】
# - 同一转移路径在不同人群中效应可能不同
# - 亚组分析可识别“高风险/高获益”人群
#
# 【典型分层】
# - 肿瘤分期：1-2 vs 3
# - CMD分期：代谢指标达标数 <3 vs >=3
# - 癌症生存率：高生存率癌症 vs 低生存率癌症
#
# 【代码逻辑（逐步）】
# 1) 读取并合并 CMD_CA、track、covariates_impute
# 2) 计算各分层变量
# 3) 按分层条件过滤得到子数据集
# 4) 保存多个亚组文件供后续模型复用
#
# 【初学者提示】
# - 分层变量建议在主分析前预定义，避免“结果导向分层”偏倚
# - 每个亚组样本量需检查，防止模型不稳定
# ==================== 脚本结尾综合概括 ====================
# 本脚本把“整体队列”拆解成“临床可解释亚群”，
# 为比较不同人群中的转移风险和生存差异提供基础。
